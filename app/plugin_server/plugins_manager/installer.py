def write_starter_adapter(
    plugin_dir: Path,
    plugin_id: str,
    class_name: str,
    *,
    display_name: str = "My Plugin",
    category: str = "general",
    author: str = "Anonymous",
) -> Path:
    """Write a starter adapter.py at plugin_dir/adapter.py.

    If adapter.py already exists, leave it alone (the user has
    already started customising it).
    """
    adapter_path = plugin_dir / "adapter.py"
    if adapter_path.exists():
        logger.info(f"adapter.py already exists at {adapter_path}; leaving alone")
        return adapter_path

    content = ADAPTER_TEMPLATE.format(
        plugin_id=plugin_id,
        class_name=class_name,
        display_name=display_name,
        category=category,
        author=author,
    )
    adapter_path.write_text(content, encoding="utf-8")
    logger.info(f"Wrote starter adapter.py at {adapter_path}")
    return adapter_path


def write_plugin_init(
    plugin_dir: Path,
    plugin_id: str,
    class_name: str,
) -> Path:
    """Write __init__.py at plugin_dir/__init__.py.

    If __init__.py already exists, leave it alone.
    """
    init_path = plugin_dir / "__init__.py"
    if init_path.exists():
        logger.info(f"__init__.py already exists at {init_path}; leaving alone")
        return init_path

    content = PLUGIN_INIT_TEMPLATE.format(
        plugin_id=plugin_id,
        class_name=class_name,
    )
    init_path.write_text(content, encoding="utf-8")
    logger.info(f"Wrote __init__.py at {init_path}")
    return init_path


