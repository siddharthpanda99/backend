"""Plugin Server — Install pipeline.

When a 3rd-party plugin is installed (via REST, CLI, or the SDK),
this module:

1. Creates the plugin folder at ``plugins/<plugin_id>/``
2. Extracts the source into ``plugins/<plugin_id>/cloned_or_extracted _repo/``
   - From a .zip: extract
   - From a git URL: git clone
   - From a local path: shutil.copytree
3. Writes a default ``adapter.py`` (the user can edit it)
4. Writes a default ``__init__.py`` (which lists the installed
   plugin so the auto-discovery walker can find it)

The user is then expected to **edit ``adapter.py``** to import
their 3rd-party code and produce one or more BaseToolPlugin
instances. The Plugin Server's auto-discovery walker picks up
the plugin on the next reload.

Folder layout produced::

    <plugins_root>/<plugin_id>/
        ├── cloned_or_extracted _repo/    # 3rd-party code (verbatim)
        ├── adapter.py                     # 3rd-party writes this
        └── __init__.py                    # auto-generated; lists the plugin
"""

from __future__ import annotations

import logging
import os
import shutil
import subprocess
import sys
import zipfile
from dataclasses import dataclass, field
from pathlib import Path
from typing import Literal

logger = logging.getLogger(__name__)


SourceType = Literal["zip", "git", "local_dir", "pip"]


@dataclass
class InstallResult:
    """Result of an install operation."""

    ok: bool
    plugin_id: str
    plugin_dir: Path
    source_type: SourceType
    message: str = ""
    errors: list[str] = field(default_factory=list)

    def to_dict(self) -> dict:
        return {
            "ok": self.ok,
            "plugin_id": self.plugin_id,
            "plugin_dir": str(self.plugin_dir),
            "source_type": self.source_type,
            "message": self.message,
            "errors": self.errors,
        }


# ───────────────────────────────────────────────────────────────────
# Source extractors
# ───────────────────────────────────────────────────────────────────


def _extract_zip(zip_path: Path, target_dir: Path) -> tuple[bool, str]:
    """Extract a .zip into target_dir."""
    try:
        with zipfile.ZipFile(zip_path, "r") as zf:
            zf.extractall(target_dir)
        return True, f"Extracted {zip_path.name}"
    except zipfile.BadZipFile as e:
        return False, f"Not a valid zip file: {e}"
    except Exception as e:
        return False, f"Zip extraction failed: {e}"


def _clone_git(url: str, target_dir: Path, *, branch: str = "main") -> tuple[bool, str]:
    """git clone into target_dir. Optional branch."""
    try:
        cmd = ["git", "clone", "--depth", "1"]
        if branch:
            cmd += ["-b", branch]
        cmd += [url, str(target_dir)]
        result = subprocess.run(
            cmd,
            capture_output=True,
            text=True,
            timeout=300,  # 5 min for slow clones
        )
        if result.returncode != 0:
            return False, f"git clone failed: {result.stderr.strip()}"
        return True, f"Cloned {url} (branch={branch})"
    except subprocess.TimeoutExpired:
        return False, "git clone timed out after 300s"
    except FileNotFoundError:
        return False, "git is not installed or not in PATH"
    except Exception as e:
        return False, f"git clone error: {e}"


def _copy_local(src_dir: Path, target_dir: Path) -> tuple[bool, str]:
    """Copy a local directory into target_dir."""
    src_dir = src_dir.resolve()
    if not src_dir.exists() or not src_dir.is_dir():
        return False, f"Source directory does not exist: {src_dir}"
    try:
        shutil.copytree(src_dir, target_dir, dirs_exist_ok=True)
        return True, f"Copied {src_dir}"
    except Exception as e:
        return False, f"Copy failed: {e}"


