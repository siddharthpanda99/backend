def _to_class_name(plugin_id: str) -> str:
    """Convert snake_case plugin id to PascalCase + 'Adapter'."""
    parts = plugin_id.replace("-", "_").split("_")
    name = "".join(p.title() for p in parts)
    if not name.endswith("Adapter"):
        name += "Adapter"
    return name


def install_plugin(
    plugin_id: str,
    *,
    source_zip: str | Path | None = None,
    source_git: str | None = None,
    source_branch: str = "main",
    source_local_dir: str | Path | None = None,
    plugins_root: str | Path | None = None,
    overwrite: bool = False,
    display_name: str | None = None,
    category: str = "general",
    author: str = "Anonymous",
) -> InstallResult:
    """Install a 3rd-party plugin from one of three sources.

    Exactly one of ``source_zip``, ``source_git``, ``source_local_dir``
    must be provided.

    Args:
        plugin_id: Stable id (snake_case).
        source_zip: Path to a .zip file to extract.
        source_git: Git URL to clone.
        source_local_dir: Local directory to copy.
        source_branch: Git branch (default 'main').
        plugins_root: Override the default plugins directory.
        overwrite: If True, replace an existing install.
        display_name: Display name for the stub adapter.
        category: Category for the stub adapter.
        author: Author for the stub adapter.

    Returns:
        InstallResult with ok=True on success.
    """
    # Validate exactly one source
    sources = {
        "zip": source_zip is not None,
        "git": source_git is not None,
        "local_dir": source_local_dir is not None,
    }
    provided = [k for k, v in sources.items() if v]
    if len(provided) != 1:
        return InstallResult(
            ok=False,
            plugin_id=plugin_id,
            plugin_dir=Path(),
            source_type="zip",  # placeholder
            errors=[f"Exactly one source required, got {len(provided)}: {provided}"],
        )

    # Validate plugin_id
    if not plugin_id.replace("_", "").replace("-", "").isalnum():
        return InstallResult(
            ok=False,
            plugin_id=plugin_id,
            plugin_dir=Path(),
            source_type="zip",
            errors=["plugin_id must be alphanumeric (with _ or - allowed)"],
        )

    # Resolve root
    if plugins_root is None:
        # Default: <plugin_server>/plugins/
        plugins_root = Path(__file__).parent.parent / "plugins"
    plugins_root = Path(plugins_root)
    plugins_root.mkdir(parents=True, exist_ok=True)

    plugin_dir = plugins_root / plugin_id
    cloned_dir = plugin_dir / "cloned_or_extracted _repo"

    # Check for existing install
    if plugin_dir.exists() and not overwrite:
        return InstallResult(
            ok=False,
            plugin_id=plugin_id,
            plugin_dir=plugin_dir,
            source_type=provided[0],
            errors=[
                f"Plugin '{plugin_id}' already exists at {plugin_dir}. "
                f"Pass overwrite=True to replace."
            ],
        )

    # Remove existing if overwriting
    if plugin_dir.exists() and overwrite:
        shutil.rmtree(plugin_dir, ignore_errors=True)

    # Create folder
    plugin_dir.mkdir(parents=True)
    cloned_dir.mkdir()

    # Extract / clone / copy
    if source_zip is not None:
        ok, msg = _extract_zip(Path(source_zip), cloned_dir)
        source_type: SourceType = "zip"
    elif source_git is not None:
        ok, msg = _clone_git(source_git, cloned_dir, branch=source_branch)
        source_type = "git"
    else:
        ok, msg = _copy_local(Path(source_local_dir), cloned_dir)
        source_type = "local_dir"

    if not ok:
        # Clean up the partial install
        shutil.rmtree(plugin_dir, ignore_errors=True)
        return InstallResult(
            ok=False,
            plugin_id=plugin_id,
            plugin_dir=plugin_dir,
            source_type=source_type,
            errors=[msg],
        )

    # Write starter adapter.py and __init__.py
    class_name = _to_class_name(plugin_id)
    try:
        write_starter_adapter(
            plugin_dir,
            plugin_id,
            class_name,
            display_name=display_name or plugin_id.replace("_", " ").title(),
            category=category,
            author=author,
        )
        write_plugin_init(plugin_dir, plugin_id, class_name)
    except Exception as e:
        shutil.rmtree(plugin_dir, ignore_errors=True)
        return InstallResult(
            ok=False,
            plugin_id=plugin_id,
            plugin_dir=plugin_dir,
            source_type=source_type,
            errors=[f"Failed to write starter files: {e}"],
        )

    logger.info(f"Installed plugin '{plugin_id}' from {source_type} into {plugin_dir}")
    return InstallResult(
        ok=True,
        plugin_id=plugin_id,
        plugin_dir=plugin_dir,
        source_type=source_type,
        message=msg,
    )


def uninstall_plugin(
    plugin_id: str,
    plugins_root: str | Path | None = None,
) -> bool:
    """Remove an installed plugin.

    Returns True if removed, False if not found.
    """
    if plugins_root is None:
        plugins_root = Path(__file__).parent.parent / "plugins"
    plugins_root = Path(plugins_root)
    plugin_dir = plugins_root / plugin_id
    if not plugin_dir.exists():
        return False
    shutil.rmtree(plugin_dir, ignore_errors=True)
    logger.info(f"Uninstalled plugin '{plugin_id}' from {plugin_dir}")
    return True


